'use strict';
// Rewrites js/version.js with the version from package.json and the current build date and time.
// Run by hand (`node scripts/stamp-version.js`) or by the GitHub Action before deploy.
const fs = require('node:fs');
const path = require('node:path');

function parts(date, timeZone, options) {
  const out = {};
  new Intl.DateTimeFormat('en-US', Object.assign({ timeZone }, options)).formatToParts(date)
    .forEach((p) => { out[p.type] = p.value; });
  return out;
}

// timeZone is optional; undefined means the machine's local zone.
function formatDate(date, timeZone) {
  const p = parts(date, timeZone, { year: 'numeric', month: '2-digit', day: '2-digit' });
  return p.year + '-' + p.month + '-' + p.day;
}

function formatTime(date, timeZone) {
  const p = parts(date, timeZone, { hour: '2-digit', minute: '2-digit', hourCycle: 'h23', timeZoneName: 'short' });
  return p.hour + ':' + p.minute + ' ' + p.timeZoneName;
}

function buildSource(version, date, timeZone) {
  const info = { version, buildDate: formatDate(date, timeZone), buildTime: formatTime(date, timeZone) };
  return [
    '// Generated by scripts/stamp-version.js. Do not edit by hand.',
    '(function (root) {',
    "  'use strict';",
    '  var info = ' + JSON.stringify(info) + ';',
    '  root.BusApp = root.BusApp || {};',
    '  root.BusApp.version = info;',
    "  if (typeof module !== 'undefined' && module.exports) module.exports = info;",
    "})(typeof window !== 'undefined' ? window : globalThis);",
    ''
  ].join('\n');
}

function hasChangelogEntry(changelog, version) {
  const escaped = version.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp('^## \\[' + escaped + '\\]', 'm').test(changelog);
}

function stamp(options) {
  const o = options || {};
  const root = o.root || path.join(__dirname, '..');
  const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
  const changelog = fs.readFileSync(path.join(root, 'CHANGELOG.md'), 'utf8');
  if (!hasChangelogEntry(changelog, version)) {
    throw new Error('CHANGELOG.md has no entry for version ' + version + '. Add "## [' + version + '] - date" first.');
  }
  const now = o.now || new Date();
  fs.writeFileSync(path.join(root, 'js', 'version.js'), buildSource(version, now, o.timeZone));
  return { version, buildDate: formatDate(now, o.timeZone), buildTime: formatTime(now, o.timeZone) };
}

module.exports = { formatDate, formatTime, buildSource, hasChangelogEntry, stamp };

if (require.main === module) {
  try {
    const r = stamp();
    console.log('Stamped js/version.js: v' + r.version + ', built ' + r.buildDate + ' ' + r.buildTime);
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
